    /* HEADER */

    document.title =
        `${data.title} — Wahyu`;


    document.getElementById("detail-year").textContent =
        data.year;


    document.getElementById("detail-title").textContent =
        data.title;


    document.getElementById("detail-description").textContent =
        data.description;


    /* PDF */

    document.getElementById("module-pdf").src =
        data.pdf;


    document.getElementById("pdf-link").href =
        data.drive;


    /* ANALISIS */

    document.getElementById("connection").textContent =
        data.connection;


    document.getElementById("challenge").textContent =
        data.challenge;


    document.getElementById("concept").textContent =
        data.concept;


    document.getElementById("change").textContent =
        data.change;


